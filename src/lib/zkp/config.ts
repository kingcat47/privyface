/**
 * 얼굴 유사도 검증을 위한 제곱합 임계값
 *
 * 특징값은 정수화되어 있으므로 (예: 418, 5951, 5000...)
 * 거리는 다음과 같이 계산됩니다 (제곱합, sqrt 없음):
 * distance = sum((governmentFeatures[i] - userFeatures[i])^2)
 *
 * 중요: 이 임계값은 제곱합 기준입니다 (sqrt를 씌우지 않음)
 * - 계산된 거리(제곱합) ≤ 임계값 → 통과
 * - 계산된 거리(제곱합) > 임계값 → 실패
 *
 * 권장 임계값 (제곱합 기준):
 * - 엄격한 검증: 200,000
 * - 일반적인 검증: 500,000
 * - 관대한 검증: 1,000,000
 * - 매우 관대한 검증: 2,000,000
 */
export const DEFAULT_SIMILARITY_THRESHOLD = 800000;
